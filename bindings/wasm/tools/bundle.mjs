/*
 * Сборка ES-модуля dist/beresta.mjs для браузеров, Workers и Node.js.
 *   node bindings/wasm/tools/bundle.mjs
 *
 * Общий JS-слой «Берёсты» (bindings/node/lib) написан в CommonJS. Браузер
 * не умеет require, а тащить ради этого webpack или rollup — лишняя
 * зависимость. Поэтому сборщик свой и простой: он обходит require от
 * точки входа, каждому модулю даёт номер, оборачивает текст модуля в
 * функцию (module, exports, require) и подменяет загрузчик аддона
 * (internal/native.js) бэкендом WebAssembly (паттерн Adapter). Подключать
 * разрешено только относительные пути: модуль Node.js (node:fs и т.п.)
 * в сборке — ошибка, а не тихая поломка в браузере.
 *
 * Building the ES module dist/beresta.mjs for browsers, Workers and Node.js.
 *   node bindings/wasm/tools/bundle.mjs
 *
 * The common Beresta JS layer (bindings/node/lib) is written in CommonJS. A browser
 * cannot require, and pulling in webpack or rollup for that is an extra
 * dependency. So the bundler is our own and simple: it walks require from the
 * entry point, gives every module a number, wraps the module text into a
 * function (module, exports, require) and substitutes the WebAssembly backend
 * for the addon loader (internal/native.js) (the Adapter pattern). Only relative
 * paths may be required: a Node.js module (node:fs and the like) in the bundle
 * is an error, not a silent breakage in a browser.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WASM_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NODE_LIB = path.resolve(WASM_DIR, '..', 'node', 'lib');
const ENTRY = path.join(NODE_LIB, 'index.js');
const BACKEND = path.join(WASM_DIR, 'lib', 'native_wasm.js');
const ALIASES = new Map([[path.join(NODE_LIB, 'internal', 'native.js'), BACKEND]]);
const REQUIRE = /require\('([^']+)'\)/g;

// Абсолютный путь подключаемого модуля с учётом подмены бэкенда
// The absolute path of a required module taking the backend substitution into account
function resolveModule(fromFile, specifier)
{
    if (!specifier.startsWith('.'))
        throw new Error('Сборка допускает только относительные пути / The bundle allows only relative paths: '
            + specifier + ' (' + fromFile + ')');
    const target = path.resolve(path.dirname(fromFile), specifier);
    if (ALIASES.has(target))
        return ALIASES.get(target);
    return target;
}

// Все модули сборки в порядке обнаружения; обход очередью, без рекурсии
// All bundle modules in discovery order; the walk uses a queue, without recursion
function collectModules()
{
    const ids = new Map([[ENTRY, 0]]);
    const order = [ENTRY];

    for (let index = 0; index < order.length; ++index)
    {
        const source = fs.readFileSync(order[index], 'utf8');
        for (const match of source.matchAll(REQUIRE))
        {
            const target = resolveModule(order[index], match[1]);
            if (ids.has(target))
                continue;
            ids.set(target, order.length);
            order.push(target);
        }
    }
    return { ids, order };
}

// Текст модуля, в котором require('путь') заменён на require(номер)
// The module text where require('path') is replaced with require(number)
function rewriteModule(file, ids)
{
    const source = fs.readFileSync(file, 'utf8');
    let result = '';
    let last = 0;

    for (const match of source.matchAll(REQUIRE))
    {
        result += source.slice(last, match.index) + 'require(' + ids.get(resolveModule(file, match[1])) + ')';
        last = match.index + match[0].length;
    }
    return result + source.slice(last);
}

// Готовый текст ES-модуля: таблица модулей, загрузчик и функция init
// The finished ES module text: the module table, the loader and the init function
function renderBundle(modules)
{
    const parts = ['// Сгенерировано tools/bundle.mjs, не редактировать / Generated by tools/bundle.mjs, do not edit',
        "import createBerestaCore from './beresta_core.mjs';", '', 'const definitions = ['];

    for (const file of modules.order)
    {
        parts.push('// ' + path.relative(WASM_DIR, file).split(path.sep).join('/'));
        parts.push('function (module, exports, require) {\n' + rewriteModule(file, modules.ids) + '\n},');
    }
    parts.push('];', fs.readFileSync(path.join(WASM_DIR, 'tools', 'bundle_runtime.mjs.txt'), 'utf8')
        .replace('@BACKEND_ID@', String(modules.ids.get(BACKEND))));
    return parts.join('\n');
}

// Точка входа: сборка модуля и копия типов TypeScript / The entry point: the module and a copy of the TypeScript types
function main()
{
    const dist = path.join(WASM_DIR, 'dist');
    const modules = collectModules();

    fs.mkdirSync(dist, { recursive: true });
    fs.writeFileSync(path.join(dist, 'beresta.mjs'), renderBundle(modules));
    fs.copyFileSync(path.join(NODE_LIB, 'index.d.ts'), path.join(dist, 'api.d.ts'));
    fs.copyFileSync(path.join(WASM_DIR, 'tools', 'beresta.d.mts.txt'), path.join(dist, 'beresta.d.mts'));
    console.log('beresta.mjs: ' + modules.order.length + ' модулей / modules');
}

main();
