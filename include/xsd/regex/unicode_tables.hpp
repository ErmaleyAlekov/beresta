#ifndef UNICODE_TABLES_HPP
#define UNICODE_TABLES_HPP

#include <cstddef>
#include <cstdint>

namespace beresta::xsd
{
    /*
    ** Таблицы символов для регулярных выражений XSD 1.0 (часть 2, приложение F).
    ** Версия Unicode — 3.1: на неё ссылается спецификация ([Unicode Database]).
    ** Категории и блоки сгенерированы скриптом tools/unicode/generate_unicode_tables.py
    ** из UnicodeData-3.1.0.txt и Blocks-4.txt; таблицы имён XML взяты из
    ** приложения B XML 1.0 (продукции [84]-[89]), на которое ссылаются \i и \c.
    ** Сторонние библиотеки (ICU и т.п.) не нужны: всё — константные массивы.
    **
    ** Character tables for XSD 1.0 regular expressions (part 2, appendix F).
    ** The Unicode version is 3.1: the specification refers to it ([Unicode Database]).
    ** The categories and blocks are generated by tools/unicode/generate_unicode_tables.py
    ** from UnicodeData-3.1.0.txt and Blocks-4.txt; the XML name tables are taken from
    ** appendix B of XML 1.0 (productions [84]-[89]), which \i and \c refer to.
    ** No third-party libraries (ICU and the like) are needed: everything is constant arrays.
    */

    // Диапазон кодов [first, last] без дополнительных данных
    // A code range [first, last] without additional data
    struct UnicodeRange
    {
        std::uint32_t first;
        std::uint32_t last;
    };

    /*
    ** Диапазон одной общей категории: major — класс (L, M, N, P, Z, S, C),
    ** minor — подкласс (u в Lu, n в Mn). Коды, не попавшие ни в один
    ** диапазон, не назначены (категория Cn).
    **
    ** A range of one general category: major is the class (L, M, N, P, Z, S, C),
    ** minor is the subclass (u in Lu, n in Mn). Codes outside every
    ** range are unassigned (the Cn category).
    */
    struct CategoryRange
    {
        std::uint32_t first;
        std::uint32_t last;
        char major;
        char minor;
    };

    // Блок Unicode: имя без пробелов, как в \p{IsИмя}, и его диапазон
    // A Unicode block: the name without spaces, as in \p{IsName}, and its range
    struct BlockRange
    {
        const char* name;
        std::uint32_t first;
        std::uint32_t last;
    };

    // Общие категории Unicode 3.1, по возрастанию кодов (unicode_category_table.cpp)
    // The Unicode 3.1 general categories, in ascending code order (unicode_category_table.cpp)
    extern const CategoryRange UNICODE_CATEGORIES[];
    extern const std::size_t UNICODE_CATEGORY_COUNT;

    // Блоки Unicode 3.1 (unicode_block_table.cpp)
    // The Unicode 3.1 blocks (unicode_block_table.cpp)
    extern const BlockRange UNICODE_BLOCKS[];
    extern const std::size_t UNICODE_BLOCK_COUNT;

    // \i: Letter | '_' | ':' по XML 1.0, приложение B (name_char_table.cpp)
    // \i: Letter | '_' | ':' by XML 1.0, appendix B (name_char_table.cpp)
    extern const UnicodeRange XML_NAME_START_RANGES[];
    extern const std::size_t XML_NAME_START_COUNT;

    // \c сверх \i: Digit | CombiningChar | Extender | '-' | '.' (name_char_table.cpp)
    // \c beyond \i: Digit | CombiningChar | Extender | '-' | '.' (name_char_table.cpp)
    extern const UnicodeRange XML_NAME_EXTRA_RANGES[];
    extern const std::size_t XML_NAME_EXTRA_COUNT;
}

#endif
